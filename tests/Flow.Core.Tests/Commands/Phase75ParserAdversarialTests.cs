    public void Parser_All1000ExplicitCommands_ResolvedToValidIntent()
    {
        int recognizedCount = 0;
        foreach (var phrase in ExplicitCommands)
        {
            var intent = _parser.Parse(phrase);
            if (intent is not UnknownCommandIntent)
            {
                recognizedCount++;
            }
        }

        // Must recognize >= 95% of explicit commands despite affixes, casing, and punctuation
        Assert.True(recognizedCount >= 950,
            $"Expected >= 950 recognized explicit commands, got {recognizedCount} out of {ExplicitCommands.Length}");
    }

