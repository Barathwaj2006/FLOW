    {
        var (coordinator, mockAsr, insertion) = CreateHarness();
        mockAsr.DefaultTranscript = proseUtterance;

        // 1. Normal Dictation session (Command Mode DISABLED)
        await coordinator.StartSessionAsync();
        Assert.Equal(SessionMode.Dictation, coordinator.CurrentMode);

        // Feed audio samples
        float[] chunk = new float[1600];
        Array.Fill(chunk, 0.2f);
        coordinator.ProcessAudioChunk(chunk);
        coordinator.ProcessAudioChunk(chunk);

        bool success = await coordinator.EndSessionAsync();

        // Invariants:
        // 1. Session succeeds
        Assert.True(success);
        // 2. Exactly 1 text insertion call
        Assert.Equal(1, insertion.InsertCallCount);
        // 3. Zero Enter keys (no \r, \n, 0x0D)
        Assert.DoesNotContain("\r", insertion.LastInsertedText!);
        Assert.DoesNotContain("\n", insertion.LastInsertedText!);
        Assert.DoesNotContain("\u000D", insertion.LastInsertedText!);
        // 4. Literal text preserved without being intercepted as a command
        Assert.False(string.IsNullOrWhiteSpace(insertion.LastInsertedText));
    }
