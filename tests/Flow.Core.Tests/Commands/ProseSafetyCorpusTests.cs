    private class CapturingInsertionService : ITextInsertionService
    {
        public string? LastInsertedText { get; private set; }
        public int InsertCallCount { get; private set; }

        public Task<InsertionResult> InsertTextAsync(string text, System.Threading.CancellationToken ct = default)
        {
            LastInsertedText = text;
            InsertCallCount++;
            return Task.FromResult(new InsertionResult(true, InsertionStrategy.UiaDirect, "TestApp", TimeSpan.FromMilliseconds(1), null, new IntPtr(100), 999, text.Length));
        }

        public Task<bool> BacktrackAsync(Flow.Core.Backtrack.InsertionRecord record, System.Threading.CancellationToken ct = default)
        {
            return Task.FromResult(true);
        }
    }

    private static (VoiceSessionCoordinator coordinator, MockASREngine mockAsr, CapturingInsertionService insertion)
        CreateHarness()
    {
        var ringBuffer = new AudioRingBuffer(10.0);
        var vad = new EnergyVAD(16000.0, energyThreshold: 0.01f, minSpeechDurationSeconds: 0.05);
        var registry = new ASREngineRegistry();
        var mockAsr = new MockASREngine();
        registry.Register(mockAsr, isDefault: true);
        var sanitizer = new DeterministicTextSanitizer();
        var insertion = new CapturingInsertionService();
        var context = new NullUIContextService(isPasswordField: false, nearbyContext: "", selectedText: "");

        var coordinator = new VoiceSessionCoordinator(
            ringBuffer,
            vad,
            registry,
            sanitizer,
            insertion,
            contextService: context
        );

        return (coordinator, mockAsr, insertion);
    }

