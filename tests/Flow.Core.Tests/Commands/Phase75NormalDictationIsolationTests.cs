        Assert.DoesNotContain('\n', insertion.LastInsertedText);
    }

    [Fact]
    public async Task ExplicitCommandActivation_Cycle_ActivationCancellationTimeout()
    {
        var (coordinator, mockAsr, _) = CreateTestHarness();

        // 1. Explicit activation via dedicated API
        await coordinator.StartCommandSessionAsync();
        Assert.Equal(SessionMode.Command, coordinator.CurrentMode);
        Assert.Equal(SessionState.Recording, coordinator.CurrentState);

        // 2. Cancellation resets to inactive
        await coordinator.CancelSessionAsync("User pressed escape");
        Assert.Equal(SessionState.Cancelled, coordinator.CurrentState);
        Assert.Equal(SessionMode.Dictation, coordinator.CurrentMode);

        // 3. Re-activation
        await coordinator.StartCommandSessionAsync();
        Assert.Equal(SessionMode.Command, coordinator.CurrentMode);

        // 4. Session end without speech cancels cleanly
        bool ended = await coordinator.EndSessionAsync();
        Assert.False(ended);
        Assert.Equal(SessionState.Cancelled, coordinator.CurrentState);
        Assert.Equal(SessionMode.Dictation, coordinator.CurrentMode);
    }

