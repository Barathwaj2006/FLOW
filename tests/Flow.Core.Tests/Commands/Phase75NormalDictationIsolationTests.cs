    [Fact]
    public async Task NormalDictation_All1000CommandLikeInputs_PermanentlyInertText_ZeroExecution()
    {
        var (coordinator, mockAsr, insertion) = CreateTestHarness();

        int processedCount = 0;
        int zeroEnterVerifiedCount = 0;

        foreach (var speechInput in ThousandCommandLikeInputs)
        {
            mockAsr.DefaultTranscript = speechInput;

            // Start standard dictation session
            await coordinator.StartSessionAsync();

            // Inviolable Assertion: Mode must strictly be Dictation
            Assert.Equal(SessionMode.Dictation, coordinator.CurrentMode);

            FeedSpeech(coordinator);

            bool completed = await coordinator.EndSessionAsync();

            // Session completed or cancelled if formatting resulted in empty
            if (completed)
            {
                processedCount++;
                string inserted = insertion.LastInsertedText ?? string.Empty;

                // 1. Inviolable Zero-Enter Check
                Assert.DoesNotContain('\r', inserted);
                Assert.DoesNotContain('\n', inserted);

                // 2. Inviolable Literal Text Check: speech is treated as plain text
                Assert.NotEmpty(inserted);
                zeroEnterVerifiedCount++;
            }
        }

        // Verify that all 1,000 cases were evaluated
        Assert.Equal(1000, ThousandCommandLikeInputs.Length);
        Assert.True(processedCount >= 990, $"Expected >= 990 successfully formatted texts, got {processedCount}");
        Assert.True(zeroEnterVerifiedCount >= 990);
    }

